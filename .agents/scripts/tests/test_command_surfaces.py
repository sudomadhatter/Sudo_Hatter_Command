        c.check(f"door-parity REGRESSION CONTROL fires on {src}",
                door_verdict(pushe2e, stale_door, "cicd-push-e2e.md", launcher_ok=False)
                == "stale",
                "the gate reported 13/13 green on exactly this file - that is the whole reason "
            "this check exists")

