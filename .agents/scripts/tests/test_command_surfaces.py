def parse_own_list(text: str) -> set[str]:
    """SCC-113: `.agents/project-own.txt`, parsed the way the ENGINE parses it.

    PowerShell (`Get-OwnAllowList`, sync-agents.ps1:310): `($_ -replace '#.*$','').Trim()`, then
    drop empties. Two parsers of one fact must agree, because a parser more generous than the
    engine's would exempt a door the engine still purges — and the keep-list only means anything
    while both sides agree about what survives a sync.

    ⭐ Agreement includes CASE. PowerShell's `-contains` (`:872`) is case-insensitive, so the
    engine keeps `Smh-Review.md` for a list saying `smh-review.md`; a case-sensitive mirror here
    would call that same door a ghost. Callers fold — see `ghost_doors`. (A BOM needs no handling:
    every caller reads through `read()`, which is `utf-8-sig`.)

    NAMES ONLY, never patterns. `*` parses to the literal filename `*`, which matches nothing on
    disk, so a malformed or hopeful list cannot widen the exemption to everything.
    """
    names = set()
    for raw in text.splitlines():
        name = raw.split("#", 1)[0].strip()
        if name:
            names.add(name)
    return names


def ghost_doors(present: list[str], sources: set[str],
                claimed: frozenset[str] = frozenset()) -> list[str]:
    """SCC-113: doors with no command source and no keep-list claim.

    EXACT names, never substrings — a prefix match would let one claim cover every sibling door.
    Case-folded on both sides, because every membership test this mirrors is a PowerShell
    `-contains`, which is case-insensitive (see `parse_own_list`).
    """
    src = {s.casefold() for s in sources}
    kept = {c.casefold() for c in claimed}
    return [n for n in present if n.casefold() not in src and n.casefold() not in kept]


def read(p: Path) -> str:
    # utf-8-SIG, not utf-8: 8 testarch-* commands carry a UTF-8 BOM. PowerShell's ReadAllLines
    # strips it, so sync-agents reads their `platforms: [opencode]` correctly - a plain utf-8 read
    # here leaves `﻿---` on line 1, which str.strip() does NOT remove (U+FEFF is not Python
    # whitespace), so the frontmatter probe misses and every one of them reads as UNIVERSAL. The
    # test then demands Claude/Codex/Antigravity doors for eight opencode-only bridges. Two parsers
    # of one file must agree byte-for-byte or the gate invents work.
    return p.read_text(encoding="utf-8-sig", errors="replace")


def ps_code_only(text: str) -> str:
    """PowerShell source with its comments removed - quote-aware, so a `#` inside a string stays.

    ⛔ A source-grep that reads comments is INVERTIBLE, and this repo has the scar twice over
    (`comment-literals-invert-source-grep-tests`). Measured on CS-18's first version: revert the
    fix at the call site, leave the deleted literal in a `# NOTE:` line above it, and all ten
    checks went green over the restored defect. Any check asking "does the CODE do X" must read
    this view; a check about PROSE reads the raw text on purpose.
    """
    out, in_block = [], False
    for line in text.splitlines():
        if in_block:
            if "#>" in line:
                line, in_block = line.split("#>", 1)[1], False
            else:
                out.append("")
                continue
        buf, quote, i = [], None, 0
        while i < len(line):
            ch = line[i]
            if quote:
                buf.append(ch)
                if ch == quote:
                    quote = None
            elif ch in "'\"":
                quote = ch
                buf.append(ch)
            elif line.startswith("<#", i):
                in_block = True
                break
            elif ch == "#":
                break
            else:
                buf.append(ch)
            i += 1
        out.append("".join(buf))
    return "\n".join(out)


def fm_field(text: str, key: str) -> str | None:
    """A frontmatter scalar, or None. Used to compare a launcher against its brain."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    for ln in lines[1:80]:
        if ln.strip() == "---":
            break
        if ln.startswith(f"{key}:"):
            return ln[len(key) + 1:].strip()
    return None


